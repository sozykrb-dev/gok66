
const S = s => new Set(s.split(' '));
const PRON = S('انا نحن انت انتي انتما انتم انتن هو هي هما هم هن');
const DEM = S('هذا هذه هذان هاتان هذين هاتين هولاء هؤلاء ذلك تلك اولئك ذاك هنا هناك');
const REL = S('الذي التي اللذان اللتان اللذين اللتين الذين اللاتي اللواتي اللائي اللاي اللي');
const PROPN = S('احمد محمد علي عمر فاطمة عائشة مصر مكة الرياض القاهرة ادم اسامة امين خالد حسن حسين ابراهيم يوسف مريم زينب سارة ليلى كريم الله بغداد دمشق عمان بيروت');
const KV = S('كان امسى اصبح اضحى ظل بات صار ليس ذهب جاء كتب قرا اكل شرب فتح قال راى سمع علم فهم درس لعب نام جلس وقف دخل خرج عاد رجع اخذ اعطى وضع حمل ركب سال اجاب وجد ترك بدا انتهى حضر سافر عمل كسر قتل ضرب نظر فعل صنع بنى زرع حفظ');
const IMP = S('اكتب اذهب افتح اقرا ادخل اخرج اجلس قم قل خذ كل تعال انظر اسمع اشرب اركب اسال ادرس افهم اعمل ارجع');
const NV = S('تفاح تمر تلميذ تاجر تاريخ تعب تاج ناس نهر نار نافذة نجم نبي نسر نهار نور يوم يمين يدين يسار ياسمين اسد ارض انسان اذن اصبع ابنه تلفاز نتيجة نظام نصر نبات يقين');
const PARTS = {
  'من':'حرف جر','الى':'حرف جر','عن':'حرف جر','على':'حرف جر','في':'حرف جر','حتى':'حرف جر أو عطف أو غاية',
  'مذ':'حرف جر','منذ':'حرف جر','رب':'حرف جر','و':'حرف عطف أو قسم','ف':'حرف عطف','ثم':'حرف عطف','او':'حرف عطف',
  'بل':'حرف عطف أو إضراب','ام':'حرف عطف أو استفهام','لكن':'حرف استدراك','ان':'حرف توكيد ونصب (إنّ، أنّ) أو حرف شرط (إنْ)',
  'لن':'حرف نصب ونفي واستقبال','كي':'حرف نصب أو تعليل','لكي':'حرف تعليل ونصب','لعل':'حرف ترجٍّ ونصب','ليت':'حرف تمنٍّ ونصب',
  'لم':'حرف نفي وجزم وقلب','لما':'حرف جزم أو ظرف','لا':'حرف نفي أو نهي أو نافية للجنس','ما':'حرف نفي أو حرف مصدري',
  'هل':'حرف استفهام','الا':'حرف استثناء أو تنبيه','لو':'حرف شرط','لولا':'حرف امتناع لوجود','يا':'حرف نداء','هيا':'حرف نداء',
  'قد':'حرف تحقيق أو تقليل','لقد':'حرف توكيد وتحقيق','سوف':'حرف استقبال','س':'حرف استقبال','بلى':'حرف جواب','نعم':'حرف جواب',
  'انما':'أداة حصر','اذا':'ظرف شرط (أداة شرط)','كلما':'ظرف شرط','اذ':'ظرف زمان'
};
Object.keys(PARTS).forEach(k => { if (k.endsWith('ى')) PARTS[k.slice(0,-1)+'ي'] = PARTS[k]; });
const NSPEC = {
  'ما':['اسم استفهام أو اسم موصول (مبني)','معرفة'],'من':['اسم استفهام أو اسم موصول (مبني)','معرفة'],
  'متى':['اسم استفهام (ظرف زمان)','اسم استفهام'],'اين':['اسم استفهام (ظرف مكان)','اسم استفهام'],
  'كيف':['اسم استفهام (حال)','اسم استفهام'],'لماذا':['اسم استفهام','اسم استفهام'],'كم':['اسم استفهام أو خبري','اسم استفهام'],
  'اي':['اسم استفهام أو شرط','اسم استفهام']
};
const ATT = ['كما','هما','كم','كن','هم','هن','ها','نا','ه','ك','ي'];
const OBJ = ['كما','هما','كم','كن','هم','هن','ها','ني','نا','ه','ك'];
const PSUF = [['تما','تاء الفاعل مع ألف التثنية'],['تم','تاء الفاعل مع ميم الجمع'],['تن','تاء الفاعل مع نون الجمع'],
  ['وا','واو الجماعة'],['نا','ضمير الفاعل «نا»'],['ت','تاء الفاعل أو تاء التأنيث'],['ن','نون النسوة'],['ا','ألف الاثنين']];
const PM = {'ي':['ياء المضارعة (غائب)',55],'ت':['تاء المضارعة (مخاطب أو غائبة)',45],'ن':['نون المضارعة (متكلمون)',45],'ا':['همزة المضارعة (متكلم)',30]};
const DEFRE = /^(?:[وف]?[بكل]?ال|[وف]?لل)(?=.{2,})/;

const norm = w => w.replace(/[\u0617-\u061A\u064B-\u0652\u0640\u0670]/g,'').replace(/[أإآٱ]/g,'ا');
const defStrict = x => PRON.has(x)||DEM.has(x)||REL.has(x)||PROPN.has(x)||DEFRE.test(x);

function presOK(x){ return x.length>=4 && /^[يتنا]/.test(x) && !x.startsWith('ال') && !NV.has(x) && !x.endsWith('ة'); }

function verbForms(w){
  const out=[];
  if (w.endsWith('ة') || w.startsWith('ال')) return out;
  if (KV.has(w)) out.push({l:'فعل ماضٍ',s:95});
  if (IMP.has(w)) out.push({l:'فعل أمر',s:92});
  if (presOK(w)) { const p=PM[w[0]]; out.push({l:'فعل مضارع محتمل: '+p[0],s:p[1]}); }
  if (w.length>=5 && w[0]==='س' && presOK(w.slice(1))) out.push({l:'فعل مضارع مسبوق بسين الاستقبال',s:50});
  for (const [s,d] of PSUF) {
    if (!w.endsWith(s)) continue;
    const st=w.slice(0,-s.length);
    if (st.length<3) continue;
    if (KV.has(st)) { out.push({l:'فعل ماضٍ متصل بـ'+d,s:88}); break; }
    if (s==='ن' && /[ايو]$/.test(st)) continue;
    out.push({l:'فعل ماضٍ محتمل متصل بـ'+d,s:(s==='ن'||s==='ا')?25:45}); break;
  }
  for (const o of OBJ) {
    if (!w.endsWith(o)) continue;
    const st=w.slice(0,-o.length);
    if (st.length<3) continue;
    if (KV.has(st)||IMP.has(st)) out.push({l:'فعل + ضمير متصل «'+o+'» في محل نصب مفعول به',s:80});
    else if (presOK(st)) out.push({l:'فعل مضارع + ضمير متصل «'+o+'» مفعول به',s:40});
    else continue;
    break;
  }
  return out;
}

function core(w, prev, next, tan){
  const P=[];
  const add=(k,l,d,s,n)=>P.push({k,l,d:d||null,s,n:n||''});
  if (PARTS[w]) add('part',PARTS[w],null,95);
  if (NSPEC[w]) add('noun',NSPEC[w][0],NSPEC[w][1],60);
  if (PRON.has(w)) add('noun','ضمير منفصل','معرفة',100);
  if (DEM.has(w)) add('noun','اسم إشارة','معرفة',100);
  if (REL.has(w)) add('noun','اسم موصول','معرفة',100);
  if (PROPN.has(w)) add('noun','اسم علم','معرفة',w==='علي'?80:98, w==='علي'?'إذا قصدت الحرف فاكتبه «على».':'');
  const m = !REL.has(w) && DEFRE.exec(w);
  if (m) add('noun', m[0].endsWith('لل') ? 'معرّف بـ«ال» (لام الجر مع «ال»)' : 'معرّف بـ«ال»','معرفة',90);
  verbForms(w).forEach(v => add('verb',v.l,null,v.s));
  const strong = P.some(p => p.k==='noun' && p.d==='معرفة' && p.s>=80);
  const hardPart = P.some(p => p.k==='part');
  if (!strong) {
    for (const a of ATT) {
      if (w.endsWith(a) && w.length-a.length>=3 && !w.endsWith('ة')) {
        add('noun','اسم مضاف إلى ضمير متصل «'+a+'»','معرفة',70,'محتمل: قد يكون الحرف الأخير من أصل الكلمة وليس ضميرًا.');
        break;
      }
    }
    if (prev==='يا') add('noun','منادى (معرفة بالنداء إن كان مفردًا مقصودًا)','معرفة',75);
    if (tan) add('noun','اسم منوّن','نكرة',90,'التنوين علامة النكرة.');
    if (next && defStrict(next) && !hardPart && !P.some(p=>p.k==='verb'&&p.s>=90))
      add('noun','اسم يتعرّف بالإضافة إلى «'+next+'»','معرفة',60,'مضاف ومضاف إليه معرفة.');
    if (!hardPart && !tan) add('noun','اسم نكرة','نكرة',P.some(p=>p.k==='verb'&&p.s>=80)?30:40);
  }
  return P;
}

function analyze(raw, prevRaw, nextRaw){
  const w=norm(raw), prev=prevRaw?norm(prevRaw):'', next=nextRaw?norm(nextRaw):'';
  const tan=/[\u064B\u064C\u064D]/.test(raw);
  let P=core(w,prev,next,tan);
  if (!PARTS[w] && w.length>=4 && /^[وف]/.test(w)) {
    const rest=w.slice(1), sub=core(rest,'',next,false).filter(p=>p.s>=80 && p.k!=='part');
    sub.forEach(p=>P.push({k:p.k,l:(w[0]==='و'?'واو العطف + ':'فاء العطف + ')+p.l,d:p.d,s:p.s-5,n:p.n}));
  }
  const seen=new Set(); P=P.filter(p=>!seen.has(p.l)&&seen.add(p.l));
  P.sort((a,b)=>b.s-a.s);
  return P;
}

export { analyze };
